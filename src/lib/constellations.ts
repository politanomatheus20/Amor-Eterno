// Curva suave (Catmull-Rom convertida em Bézier) passando pelos pontos.
export function smoothPath(points: Point[], closed: boolean) {
  const n = points.length;
  const at = (i: number) =>
    closed ? points[(i + n) % n] : points[Math.min(Math.max(i, 0), n - 1)];
  let d = `M${points[0][0]} ${points[0][1]}`;
  const last = closed ? n : n - 1;
  for (let i = 0; i < last; i++) {
    const [x0, y0] = at(i - 1);
    const [x1, y1] = at(i);
    const [x2, y2] = at(i + 1);
    const [x3, y3] = at(i + 2);
    const c1x = x1 + (x2 - x0) / 6;
    const c1y = y1 + (y2 - y0) / 6;
    const c2x = x2 - (x3 - x1) / 6;
    const c2y = y2 - (y3 - y1) / 6;
    d += ` C${c1x.toFixed(1)} ${c1y.toFixed(1)} ${c2x.toFixed(1)} ${c2y.toFixed(1)} ${x2} ${y2}`;
  }
  return closed ? `${d} Z` : d;
}
